"""Live Soundscape, Room Tone & SFX Audio Mixer (v3.0.0).

Materializes the `soundscape` plan generated by `director.py` (room tone bed +
timestamped procedural SFX events) and mixes it cleanly into any rendered video
via `-filter_complex_script` (`adelay` + `amix` + video stream copy `-c:v copy`
so video is NEVER re-encoded!). Zero external dependencies.
"""

from __future__ import annotations

import os
import shutil
import tempfile
from typing import Any

from ..soundscape import generate_room_tone, synthesize_sfx
from .filtergraph import run_ffmpeg_with_script


def materialize_soundscape_audio(
    soundscape: dict[str, Any],
    total_duration: float,
    work_dir: str,
) -> dict[str, Any]:
    """Synthesize room tone and all planned SFX WAV files into `work_dir`."""
    os.makedirs(work_dir, exist_ok=True)
    dur = max(0.5, float(total_duration))
    room_tone_path: str | None = None
    rt_preset = soundscape.get("room_tone")
    if rt_preset:
        rt_out = os.path.join(work_dir, "room_tone.wav")
        rt_db = soundscape.get("room_tone_db", -38.0)
        ok_r, _ = generate_room_tone(rt_out, duration=dur, preset=str(rt_preset), volume_db=float(rt_db))
        if ok_r:
            room_tone_path = rt_out

    sfx_files: list[dict[str, Any]] = []
    # Cache identical SFX kinds so we synthesize each kind at most once
    kind_cache: dict[str, str] = {}
    for ev in soundscape.get("sfx_events") or []:
        kind = str(ev.get("kind") or "").strip().lower()
        t_sec = max(0.0, float(ev.get("time", 0.0)))
        if not kind or t_sec >= dur:
            continue
        if kind not in kind_cache:
            sfx_out = os.path.join(work_dir, f"sfx_{kind}.wav")
            ok_s, _ = synthesize_sfx(kind, sfx_out)
            if ok_s:
                kind_cache[kind] = sfx_out
        if kind in kind_cache:
            sfx_files.append({
                "kind": kind,
                "time": round(t_sec, 3),
                "path": kind_cache[kind],
            })

    return {
        "room_tone_path": room_tone_path,
        "sfx_files": sfx_files,
        "duration": round(dur, 3),
    }


def mix_soundscape_into_video(
    video_path: str,
    output_path: str,
    soundscape: dict[str, Any],
    total_duration: float,
    timeout: int = 180,
) -> tuple[bool, dict[str, Any]]:
    """Mix synthesized room tone + timestamped SFX into `video_path` without re-encoding video.

    Uses `-c:v copy` (instantaneous, zero quality loss) and mixes audio streams
    with `adelay` + `amix=inputs=N:duration=first:normalize=0` via `-filter_complex_script`.
    """
    if not video_path or not os.path.isfile(video_path):
        return False, {"code": "FILE_NOT_FOUND", "message": f"Video not found: {video_path!r}"}

    with tempfile.TemporaryDirectory(prefix="agentcut-mix-") as td:
        mat = materialize_soundscape_audio(soundscape, total_duration, td)
        extra_tracks: list[tuple[str, int]] = []  # (path, delay_ms)
        if mat["room_tone_path"]:
            extra_tracks.append((mat["room_tone_path"], 0))
        for sfx in mat["sfx_files"]:
            extra_tracks.append((sfx["path"], int(round(sfx["time"] * 1000))))

        if not extra_tracks:
            if os.path.abspath(video_path) != os.path.abspath(output_path):
                shutil.copy2(video_path, output_path)
            return True, {"output": output_path, "mixed_tracks": 0}

        inputs = ["-i", video_path]
        fg_lines = ["[0:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo[a0]"]
        mix_labels = ["[a0]"]

        for idx, (tpath, delay_ms) in enumerate(extra_tracks, start=1):
            inputs.extend(["-i", tpath])
            lbl = f"[a{idx}]"
            if delay_ms > 0:
                fg_lines.append(
                    f"[{idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,"
                    f"adelay={delay_ms}|{delay_ms}{lbl}"
                )
            else:
                fg_lines.append(
                    f"[{idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo{lbl}"
                )
            mix_labels.append(lbl)

        fg_lines.append(
            f"{''.join(mix_labels)}amix=inputs={len(mix_labels)}:duration=first:dropout_transition=2:normalize=0,"
            f"alimiter=limit=0.95[aout]"
        )
        fg = ";\n".join(fg_lines)

        same_file = os.path.abspath(video_path) == os.path.abspath(output_path)
        target_out = os.path.join(td, "mixed.mp4") if same_file else output_path
        ok, res = run_ffmpeg_with_script(
            inputs=inputs,
            filter_graph=fg,
            output_args=["-map", "0:v", "-map", "[aout]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest"],
            output_path=target_out,
            timeout=timeout,
            work_dir=td,
        )
        if not ok:
            return False, res
        if same_file:
            os.replace(target_out, output_path)

        return True, {
            "output": output_path,
            "mixed_tracks": len(extra_tracks),
            "room_tone": bool(mat["room_tone_path"]),
            "sfx_count": len(mat["sfx_files"]),
        }
