"""Live Soundscape, Generative Ambient Music, Sidechain Ducking & J-Cut Voice Mixer (v3.3.6).

Materializes the `soundscape` plan generated by `director.py` (room tone bed +
generative ambient music bed + timestamped procedural SFX events + J-Cut overlapped
scene narrations) and mixes it cleanly into any rendered video via
`-filter_complex_script` with true `sidechaincompress` dynamic ducking and
`-c:v copy` (zero video re-encoding!).
Zero external dependencies.
"""

from __future__ import annotations

import os
import shutil
import tempfile
from typing import Any

from ..soundscape import generate_ambient_music_bed, generate_room_tone, synthesize_sfx
from .filtergraph import run_ffmpeg_with_script


def materialize_soundscape_audio(
    soundscape: dict[str, Any],
    total_duration: float,
    work_dir: str,
) -> dict[str, Any]:
    """Synthesize room tone, generative music bed, and planned SFX WAV files into `work_dir`."""
    os.makedirs(work_dir, exist_ok=True)
    dur = max(0.5, float(total_duration))

    room_tone_path: str | None = None
    rt_preset = soundscape.get("room_tone")
    if rt_preset:
        rt_out = os.path.join(work_dir, "room_tone.wav")
        rt_db = soundscape.get("room_tone_db", -38.0)
        ok_r, _ = generate_room_tone(rt_out, duration=dur, preset=str(rt_preset), volume_db=float(rt_db))
        if ok_r:
            room_tone_path = rt_out

    music_bed_path: str | None = None
    mb_preset = soundscape.get("music_bed")
    if isinstance(mb_preset, str) and mb_preset.strip():
        if os.path.isfile(mb_preset):
            music_bed_path = mb_preset
        else:
            mb_out = os.path.join(work_dir, "music_bed.wav")
            mb_db = float(soundscape.get("music_bed_db", -22.0))
            ok_m, _ = generate_ambient_music_bed(mb_out, duration=dur, preset=mb_preset, volume_db=mb_db)
            if ok_m:
                music_bed_path = mb_out

    sfx_files: list[dict[str, Any]] = []
    kind_cache: dict[str, str] = {}
    for ev in soundscape.get("sfx_events") or []:
        kind = str(ev.get("kind") or "").strip().lower()
        t_sec = max(0.0, float(ev.get("time", 0.0)))
        if not kind or t_sec >= dur:
            continue
        if kind not in kind_cache:
            sfx_out = os.path.join(work_dir, f"sfx_{kind}.wav")
            ok_s, _ = synthesize_sfx(kind, sfx_out)
            if ok_s:
                kind_cache[kind] = sfx_out
        if kind in kind_cache:
            sfx_files.append({
                "kind": kind,
                "time": round(t_sec, 3),
                "path": kind_cache[kind],
            })

    return {
        "room_tone_path": room_tone_path,
        "music_bed_path": music_bed_path,
        "sfx_files": sfx_files,
        "duration": round(dur, 3),
    }


def mix_soundscape_into_video(
    video_path: str,
    output_path: str,
    soundscape: dict[str, Any],
    total_duration: float,
    scenes: list[dict[str, Any]] | None = None,
    timeout: int = 180,
) -> tuple[bool, dict[str, Any]]:
    """Mix J-Cut overlapped narration, room tone, sidechain-ducked music bed, and SFX into `video_path` (`-c:v copy`)."""
    if not video_path or not os.path.isfile(video_path):
        return False, {"code": "FILE_NOT_FOUND", "message": f"Video not found: {video_path!r}"}

    with tempfile.TemporaryDirectory(prefix="agentcut-mix-") as td:
        mat = materialize_soundscape_audio(soundscape, total_duration, td)
        has_music = bool(mat["music_bed_path"])
        use_sidechain = bool(soundscape.get("sidechain_ducking", True)) and has_music

        # Check if scenes carry active J-Cut audio leads with valid narration files
        jcut_scenes: list[dict[str, Any]] = []
        j_cuts_applied = 0
        if scenes and len(scenes) >= 2:
            all_valid = all(
                isinstance(s.get("narration"), str) and os.path.isfile(str(s["narration"]))
                for s in scenes
            )
            has_lead = any(
                float(s.get("audio_start", s.get("start", 0.0))) < float(s.get("start", 0.0)) - 0.005
                for s in scenes[1:]
            )
            if all_valid and has_lead:
                jcut_scenes = list(scenes)
                j_cuts_applied = sum(
                    1
                    for s in scenes[1:]
                    if float(s.get("audio_start", s.get("start", 0.0))) < float(s.get("start", 0.0)) - 0.005
                )

        extra_tracks: list[tuple[str, int]] = []  # (path, delay_ms) for non-ducked layers
        if mat["room_tone_path"]:
            extra_tracks.append((mat["room_tone_path"], 0))
        for sfx in mat["sfx_files"]:
            extra_tracks.append((sfx["path"], int(round(sfx["time"] * 1000))))

        if not extra_tracks and not has_music and not jcut_scenes:
            if os.path.abspath(video_path) != os.path.abspath(output_path):
                shutil.copy2(video_path, output_path)
            return True, {
                "output": output_path,
                "mixed_tracks": 0,
                "room_tone": False,
                "music_bed": False,
                "sidechain_ducking": False,
                "j_cuts_applied": 0,
                "sfx_count": 0,
            }

        inputs = ["-i", video_path]
        fg_lines: list[str] = []
        mix_labels: list[str] = []
        next_idx = 1

        # Build the primary voice stream [v_src]: either J-Cut overlapped scene narrations or [0:a]
        if jcut_scenes:
            v_lbls: list[str] = []
            for si, sc in enumerate(jcut_scenes):
                inputs.extend(["-i", str(sc["narration"])])
                s_idx = next_idx
                next_idx += 1
                a_start = max(0.0, float(sc.get("audio_start", sc.get("start", 0.0))))
                delay_ms = int(round(a_start * 1000))
                vl = f"[vj{si}]"
                if delay_ms > 0:
                    fg_lines.append(
                        f"[{s_idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,"
                        f"afade=t=in:st=0:d=0.04,adelay={delay_ms}|{delay_ms}{vl}"
                    )
                else:
                    fg_lines.append(
                        f"[{s_idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo{vl}"
                    )
                v_lbls.append(vl)
            fg_lines.append(
                f"{''.join(v_lbls)}amix=inputs={len(v_lbls)}:duration=longest:dropout_transition=0:normalize=0,"
                f"apad=whole_dur={max(0.5, float(total_duration)):.3f}[v_src]"
            )
            voice_source_label = "[v_src]"
        else:
            fg_lines.append("[0:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo[v_src]")
            voice_source_label = "[v_src]"

        if has_music and mat["music_bed_path"]:
            inputs.extend(["-i", mat["music_bed_path"]])
            m_idx = next_idx
            next_idx += 1
            if use_sidechain:
                ratio = float(soundscape.get("duck_ratio", 4.5))
                attack = int(soundscape.get("duck_attack_ms", 35))
                release = int(soundscape.get("duck_release_ms", 420))
                fg_lines.append(f"{voice_source_label}asplit=2[v_main][v_sc]")
                fg_lines.append(
                    f"[{m_idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo[m_raw]"
                )
                fg_lines.append(
                    f"[m_raw][v_sc]sidechaincompress=threshold=0.025:ratio={ratio:.1f}:attack={attack}:release={release}[m_ducked]"
                )
                mix_labels.extend(["[v_main]", "[m_ducked]"])
            else:
                fg_lines.append(
                    f"[{m_idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo[m_bed]"
                )
                mix_labels.extend([voice_source_label, "[m_bed]"])
        else:
            mix_labels.append(voice_source_label)

        for tpath, delay_ms in extra_tracks:
            inputs.extend(["-i", tpath])
            idx = next_idx
            next_idx += 1
            lbl = f"[a{idx}]"
            if delay_ms > 0:
                fg_lines.append(
                    f"[{idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,"
                    f"adelay={delay_ms}|{delay_ms}{lbl}"
                )
            else:
                fg_lines.append(
                    f"[{idx}:a]aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo{lbl}"
                )
            mix_labels.append(lbl)

        if len(mix_labels) == 1:
            fg_lines.append(f"{mix_labels[0]}alimiter=limit=0.95[aout]")
        else:
            fg_lines.append(
                f"{''.join(mix_labels)}amix=inputs={len(mix_labels)}:duration=first:dropout_transition=2:normalize=0,"
                f"alimiter=limit=0.95[aout]"
            )
        fg = ";\n".join(fg_lines)

        same_file = os.path.abspath(video_path) == os.path.abspath(output_path)
        target_out = os.path.join(td, "mixed.mp4") if same_file else output_path
        ok, res = run_ffmpeg_with_script(
            inputs=inputs,
            filter_graph=fg,
            output_args=["-map", "0:v", "-map", "[aout]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest"],
            output_path=target_out,
            timeout=timeout,
            work_dir=td,
        )
        if not ok:
            return False, res
        if same_file:
            os.replace(target_out, output_path)

        return True, {
            "output": output_path,
            "mixed_tracks": len(extra_tracks) + (1 if has_music else 0),
            "room_tone": bool(mat["room_tone_path"]),
            "music_bed": has_music,
            "music_preset": soundscape.get("music_bed") if has_music else None,
            "sidechain_ducking": use_sidechain,
            "j_cuts_applied": j_cuts_applied,
            "sfx_count": len(mat["sfx_files"]),
        }
